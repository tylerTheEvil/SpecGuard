"""Spec Kit integration pilot — Phase 0 of docs/speckit_integration_plan.md.

Runs the deterministic SpecGuard pipeline (default profile) over a corpus of
spec-kit-style feature specifications and reports per-detector trigger
frequencies, gate distributions, and every individual hit — the raw material
for the false-positive classification in results/speckit_pilot/pilot_report.md.

Corpus: experiments/speckit_pilot/specs/*/spec.md — six specs generated by
an LLM agent (Claude Opus 4.8) faithfully following spec-kit v0.13's
spec-template.md + specify.md instructions (the same generation process the
real /speckit.specify command drives). Representativeness caveats are in the
pilot report.

Usage:
    python experiments/speckit_pilot/run_pilot.py [--profile speckit] [--json OUT]

`--profile speckit` SIMULATES the calibrated profile proposed for Phase 2.
The rules below were derived from manual classification of the raw
(default-profile) run — see the hit-by-hit table in pilot_report.md. They
split into two groups, kept separate on purpose:

  GENERAL detector/scorer fixes (register-independent bugs the pilot exposed;
  candidates for the core, not just the profile):
    G1  comma-grouped numerals ("1,000") tokenize as "000" → MISSING_UNIT FP
    G2  "how many" interrogative collides with VAGUENESS 'many'
    G3  calendar units (day/week/month/year) missing from the unit lexicon
        while min/hours are present in the MISSING_UNIT exclusion → "12 months"
        flagged despite having a unit
    G4  noun-phrase collisions: "lower/upper limit|bound|threshold" is not a
        baseline-less comparative
    G5  measurable-criterion pattern `(?:%|percent)\b` — `\b` after '%' never
        matches before whitespace, so "90%" is never counted as measurable
        (also: under/within/no more than comparators and min/minute/hour units
        absent from MEASURABLE_PATTERNS though present elsewhere)

  SPECKIT-register rules (product-spec idiom, would stay profile-scoped):
    P1  counts of discrete entities ("1000 concurrent users", "500 photos",
        "top 5 endpoints") are unit-less by nature → MISSING_UNIT suppressed
    P2  'any' is the universal quantifier in product specs ("reject any
        expired code") — precise and testable → VAGUENESS suppressed
    P3  Success Criteria are modal-free outcome statements BY DESIGN (spec-kit
        Success Criteria Guidelines) → for kind=SC, modal strength is treated
        as mandatory-equivalent instead of absent

Not simulated (residual, documented): 'larger' in "a larger single-photo
view" stays flagged — no clean mechanical rule; 1 residual FP in the corpus.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

from specguard.core.pipeline import AssessmentResult, aggregate_metrics
from specguard.core.quality_scorer import (
    MEASURABLE_PATTERNS,
    SEVERITY_WEIGHTS,
    SMELL_AFFECTS_COMPLETENESS,
    SMELL_AFFECTS_VERIFIABILITY,
    QualityScores,
    _modal_strength,
    score_requirement,
)
from specguard.core.smell_detector import SmellHit, SmellReport, SmellType, analyze_requirement

SPECS_DIR = Path(__file__).parent / "specs"

# Matches spec-kit requirement bullets: "- **FR-001**: text" / "- **SC-001**: text"
REQ_BULLET = re.compile(r"^- \*\*(?P<id>(?:FR|SC)-\d{3})\*\*:\s*(?P<text>.+)$")

CALENDAR_UNITS = r"(?:day|days|week|weeks|month|months|year|years)"

# G5 remediation preview: quantifications the default MEASURABLE_PATTERNS miss.
EXTRA_MEASURABLE = [
    re.compile(r"\d+\s*%"),                                   # 90% (no trailing \b)
    re.compile(r"\b(?:under|within|no more than|at most|exactly|every)\b", re.I),
    re.compile(r"\b\d+[\d,]*\s*(?:min|minute|minutes|hour|hours|" + CALENDAR_UNITS[3:], re.I),
    re.compile(r"\b\d{1,3}(?:,\d{3})+\b"),                    # comma-grouped numeral
    re.compile(r"\bzero\s+[a-z]+", re.I),                     # "zero orders", "zero data loss"
]


def extract_requirements(spec_path: Path) -> list[tuple[str, str, str]]:
    """Extract (req_id, kind, text) from a spec-kit spec.md.

    Only FR-### and SC-### bullets are extracted (pilot scope; user stories
    and acceptance scenarios wait for the Phase 1 parser).
    """
    out = []
    for line in spec_path.read_text(encoding="utf-8").splitlines():
        m = REQ_BULLET.match(line.strip())
        if m:
            kind = m.group("id").split("-")[0]  # FR | SC
            text = re.sub(r"\*\*(.+?)\*\*", r"\1", m.group("text")).strip()
            out.append((m.group("id"), kind, text))
    return out


def speckit_keep_hit(hit: SmellHit, text: str) -> bool:
    """Hit-level rules G1-G4 + P1-P2. Return True to KEEP the hit."""
    t = hit.trigger.lower()
    before = text[max(0, hit.position - 12):hit.position].lower()
    after = text[hit.position:hit.position + 45]

    if hit.smell_type is SmellType.MISSING_UNIT:
        if before.rstrip().endswith(","):                      # G1: "1,000" → "000"
            return False
        if re.match(r"\d+\s+" + CALENDAR_UNITS + r"\b", after, re.I):  # G3: "12 months"
            return False
        # P1: count of discrete entities — number followed by (optional adjective +)
        # plural noun ("500 photos", "1000 concurrent users", "5 endpoints")
        if re.match(r"\d+\s+(?:[a-z]+\s+)?[a-z]+(?:s|ren)\b", after):
            return False

    if hit.smell_type is SmellType.VAGUENESS:
        if t == "many" and before.rstrip().endswith("how"):    # G2: "how many"
            return False
        if t == "any":                                         # P2: universal quantifier
            return False

    if hit.smell_type is SmellType.COMPARATIVE and re.match(  # noqa: SIM103 — keep rule-list symmetry
        r"(?:lower|higher|larger|smaller)\s+(?:limit|bound|threshold)s?\b", after, re.I
    ):                                                         # G4: noun phrase
        return False

    return True


def speckit_score(text: str, report: SmellReport, kind: str) -> QualityScores:
    """Scorer with G5 + P3 applied — mirrors quality_scorer.score_requirement.

    Kept in lock-step with the core scorer's structure so the simulation
    isolates exactly two changes: the extended measurable lexicon (G5) and
    SC modal neutrality (P3).
    """
    measurable = any(p.search(text) for p in MEASURABLE_PATTERNS) or any(
        p.search(text) for p in EXTRA_MEASURABLE
    )
    if kind == "SC":
        # P3: outcome register — a modal-free SC is correct style, so the
        # completeness modal bonus is granted unconditionally. But for
        # verifiability, measurability becomes the DOMINANT factor: an SC
        # without a quantified criterion must not pass on style alone
        # (spec-kit's own checklist: "Success criteria are measurable").
        # Unmeasurable SC → V=0.4 → overall ≈0.70 → WARN.
        modal = 1.0
        v = 0.4 + (0.6 if measurable else 0.0)
    else:
        modal = _modal_strength(text)
        v = 0.5 + (0.3 if measurable else 0.0) + 0.2 * modal
    v -= sum(SEVERITY_WEIGHTS[h.severity] for h in report.hits
             if h.smell_type in SMELL_AFFECTS_VERIFIABILITY)
    v = round(max(0.0, min(1.0, v)), 3)

    c = 0.7 + (0.2 if modal > 0 else 0.0)
    if re.search(r"\b[A-Z][A-Z0-9]{2,}\b", text):
        c += 0.1
    c -= sum(SEVERITY_WEIGHTS[h.severity] * 1.5 for h in report.hits
             if h.smell_type is SmellType.PLACEHOLDER)
    c -= sum(SEVERITY_WEIGHTS[h.severity] for h in report.hits
             if h.smell_type in SMELL_AFFECTS_COMPLETENESS)
    c = round(max(0.0, min(1.0, c)), 3)

    # consistency unchanged — reuse core implementation via score_requirement
    s = score_requirement(text, SmellReport(report.requirement_id, text, [])).consistency

    overall = round(0.30 * c + 0.25 * s + 0.45 * v, 3)
    return QualityScores(report.requirement_id, c, s, v, overall)


def assess(reqs: list[tuple[str, str, str, str]], profile: str) -> list[AssessmentResult]:
    results = []
    for spec, req_id, kind, text in reqs:
        report = analyze_requirement(f"{spec}/{req_id}", text)
        if profile == "speckit":
            report = SmellReport(
                requirement_id=report.requirement_id,
                requirement_text=report.requirement_text,
                hits=[h for h in report.hits if speckit_keep_hit(h, text)],
            )
            scores = speckit_score(text, report, kind)
        else:
            scores = score_requirement(text, report)
        results.append(
            AssessmentResult(
                requirement_id=f"{spec}/{req_id}",
                requirement_text=text,
                smell_report=report,
                quality_scores=scores,
                metadata={"spec": spec, "kind": kind},
            )
        )
    return results


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--profile", choices=["default", "speckit"], default="default")
    ap.add_argument("--json", type=Path, default=None, help="write raw results JSON")
    args = ap.parse_args(argv)

    reqs = []
    for spec_md in sorted(SPECS_DIR.glob("*/spec.md")):
        spec = spec_md.parent.name
        for req_id, kind, text in extract_requirements(spec_md):
            reqs.append((spec, req_id, kind, text))
    if not reqs:
        print("no requirements found", file=sys.stderr)
        return 1

    results = assess(reqs, args.profile)

    agg = aggregate_metrics(results)
    fr = [r for r in results if r.metadata["kind"] == "FR"]
    sc = [r for r in results if r.metadata["kind"] == "SC"]

    print(f"profile={args.profile}  corpus: {len(fr)} FR + {len(sc)} SC "
          f"from {len({r.metadata['spec'] for r in results})} specs\n")

    for label, subset in [("ALL", results), ("FR", fr), ("SC", sc)]:
        a = aggregate_metrics(subset)
        print(f"  {label:3s}  PASS {a['gate_pass']:3d}  WARN {a['gate_warn']:3d}  "
              f"FAIL {a['gate_fail']:3d}   pass_rate {a['pass_rate']:.3f}   "
              f"smells/req {a['smells_per_requirement']:.2f}   "
              f"avg C/S/V {a['avg_completeness']:.2f}/{a['avg_consistency']:.2f}/"
              f"{a['avg_verifiability']:.2f}")

    print("\nsmell type distribution (hits):")
    for stype, n in sorted(agg["smell_type_distribution"].items(), key=lambda x: -x[1]):
        print(f"  {stype:20s} {n:4d}")

    print("\ntrigger frequency:")
    trig = Counter()
    for r in results:
        for h in r.smell_report.hits:
            trig[(h.smell_type.value, h.trigger.lower(), h.severity)] += 1
    for (stype, t, sev), n in trig.most_common(25):
        print(f"  {n:3d}  {stype:20s} {sev:6s}  '{t}'")

    print("\nnon-PASS requirements:")
    for r in results:
        if r.gate_decision != "PASS":
            trigs = ", ".join(f"{h.smell_type.value}:'{h.trigger}'" for h in r.smell_report.hits)
            print(f"  {r.gate_decision:4s} {r.quality_scores.overall:.2f}  "
                  f"{r.requirement_id:24s} {trigs}")
            print(f"        | {r.requirement_text[:110]}")

    print("\nper-spec:")
    by_spec: dict[str, list[AssessmentResult]] = defaultdict(list)
    for r in results:
        by_spec[r.metadata["spec"]].append(r)
    for spec, rs in sorted(by_spec.items()):
        a = aggregate_metrics(rs)
        print(f"  {spec:24s} PASS {a['gate_pass']:2d} WARN {a['gate_warn']:2d} "
              f"FAIL {a['gate_fail']:2d}  smells/req {a['smells_per_requirement']:.2f}")

    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        payload = {
            "profile": args.profile,
            "aggregate": agg,
            "results": [
                {
                    "id": r.requirement_id,
                    "spec": r.metadata["spec"],
                    "kind": r.metadata["kind"],
                    "text": r.requirement_text,
                    "gate": r.gate_decision,
                    "scores": {
                        "completeness": r.quality_scores.completeness,
                        "consistency": r.quality_scores.consistency,
                        "verifiability": r.quality_scores.verifiability,
                        "overall": r.quality_scores.overall,
                    },
                    "hits": [
                        {
                            "type": h.smell_type.value,
                            "trigger": h.trigger,
                            "severity": h.severity,
                            "position": h.position,
                        }
                        for h in r.smell_report.hits
                    ],
                }
                for r in results
            ],
        }
        args.json.write_text(json.dumps(payload, indent=2), encoding="utf-8")
        print(f"\nwrote {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
